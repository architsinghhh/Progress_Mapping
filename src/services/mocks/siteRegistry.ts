function simpleMissions(
  prefix: string,
  startIso: string,
  labels: string[],
  coverageHa: number,
  notes: string[],
): SurveyMission[] {
  const start = new Date(startIso)
  return labels.map((label, i) => {
    const d = new Date(start)
    d.setMonth(d.getMonth() + i * 6)
    const iso = d.toISOString().slice(0, 10)
    return {
      id: `${prefix}_m${i}`,
      date: iso,
      label,
      dayOffset: i * 183,
      notes: notes[i] ?? `${label} — 6‑month cadence survey.`,
      layers: i === 0 ? ['ortho', 'dem', 'contours'] : ['ortho', 'dem', 'contours', 'model'],
      gsdCm: Math.max(2.0, 2.8 - i * 0.1),
      altitudeM: 120 - i * 3,
      droneId: i % 2 === 0 ? 'AJN-M300-07' : 'AJN-M300-09',
      coverageHa,
      constructionStage: Math.min(6, i + 1) as ConstructionStageId,
    }
  })
}


export function getProgressForZone(zoneId: string): ProgressItem[] {
  const rows = progressByZone[zoneId] ?? []
  // Greenfield is a completed 3-year delivery — scrub timeline scales from 100% closure
  return rows.map((item) => ({
    ...item,
    plannedPercent: 100,
    onsitePercent: 100,
    status: 'completed' as const,
    remark: item.status === 'completed' ? item.remark : 'Closed on plan · as-built verified',
    lastUpdated: '2026-08-08',
  }))
}

